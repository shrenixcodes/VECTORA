const edge = (g: { edges: GraphEdge[] }, type: string, from: string, to: string) =>
  g.edges.find((e) => e.type === type && e.source.endsWith(from) && e.target.endsWith(to));

describe('file scanning and ignore handling', () => {
  it('respects .gitignore, skips binaries and reports what it skipped', async () => {
    const scan = await scanRepository(SAMPLE);
    const paths = scan.files.map((f) => f.path);
    expect(paths).toContain('web/src/server.ts');
    expect(paths).not.toContain('ignored/skip.ts');
    expect(scan.skipped.ignored).toBeGreaterThan(0);
    expect(scan.files.every((f) => /^[0-9a-f]{40}$/.test(f.hash))).toBe(true);
  });

  it('applies custom ignore patterns, size limits, binary and generated detection', async () => {
    const dir = tempDir('scan');
    writeTree(dir, {
      'src/a.ts': 'export const a = 1;\n',
      'src/big.ts': `export const big = "${'x'.repeat(5000)}";\n`,
      'src/gen.ts': '// @generated by tool\nexport const g = 1;\n',
      'secret/key.ts': 'export const k = 1;\n',
      'node_modules/pkg/index.js': 'module.exports = 1;\n',
      'logo.png': 'not really a png',
    });
    fs.writeFileSync(path.join(dir, 'blob.dat2'), Buffer.from([1, 2, 0, 3, 0, 0]));
    const scan = await scanRepository(dir, { ignorePatterns: ['secret/'], maxFileSizeBytes: 2000 });
    expect(scan.files.map((f) => f.path)).toEqual(['src/a.ts']);
    expect(scan.skipped).toMatchObject({ ignored: 1, oversized: 1, generated: 1 });
    expect(scan.skipped.binary).toBe(2);
  });

  it('does not follow symbolic links out of the repository', async () => {
    const dir = tempDir('symlink');
    const outside = tempDir('symlink-outside');
    writeTree(outside, { 'private.ts': 'export const secret = 1;\n' });
    writeTree(dir, { 'a.ts': 'export const a = 1;\n' });
    try {
      fs.symlinkSync(path.join(outside, 'private.ts'), path.join(dir, 'link.ts'), 'file');
      fs.symlinkSync(outside, path.join(dir, 'linked-dir'), 'junction');
    } catch {
      return; // creating links needs a privilege this machine does not grant; nothing to verify
    }
    const scan = await scanRepository(dir);
    expect(scan.files.map((f) => f.path)).toEqual(['a.ts']);
  });

  it('truncates at the file limit and prefers analysable sources', async () => {
    const dir = tempDir('limit');
    const files: Record<string, string> = {};
    for (let i = 0; i < 30; i++) files[`notes/n${i}.txt`] = 'note\n';
    for (let i = 0; i < 10; i++) files[`src/m${i}.ts`] = `export const v${i} = ${i};\n`;
    writeTree(dir, files);
    const scan = await scanRepository(dir, { maxFiles: 12 });
    expect(scan.truncated).toBe(true);
    expect(scan.files).toHaveLength(12);
    expect(scan.files.filter((f) => f.language === 'typescript')).toHaveLength(10);
  });

  it('detects languages, configuration, tests and generated files', () => {
    expect(detectLanguage('a/b.tsx')).toBe('typescript');
    expect(detectLanguage('Dockerfile')).toBe('dockerfile');
    expect(detectLanguage('x.unknownext')).toBeNull();
    expect(isConfigFile('package.json')).toBe(true);
    expect(isConfigFile('src/app.ts')).toBe(false);
    expect(isTestFile('src/a.test.ts')).toBe(true);
    expect(isTestFile('pkg/test_x.py')).toBe(true);
    expect(looksGenerated('a.min.js', '')).toBe(true);
    expect(looksGenerated('a.ts', 'const x = 1;\n')).toBe(false);
  });

  it('reads manifests: dependencies, frameworks, entry points and description', async () => {
    const scan = await scanRepository(SAMPLE);
    const m = readManifests(SAMPLE, scan.files);
    expect(m.dependencies.map((d) => d.name)).toEqual(
      expect.arrayContaining(['express', 'drizzle-orm', 'fastapi', 'sqlalchemy', 'serde']),
    );
    expect(m.frameworks.map((f) => f.name)).toEqual(expect.arrayContaining(['Express', 'FastAPI', 'React']));
    expect(m.declaredEntryPoints.map((e) => e.path)).toContain('web/src/server.ts');
    expect(m.description).toMatch(/note-taking/);
    expect(m.goModules[0]).toMatchObject({ module: 'example.com/orbit/tools' });
  });
});

