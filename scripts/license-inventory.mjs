// Generates docs/LICENSES.md: every package in the production dependency closure of the
// workspaces, with its version and declared licence. Reads package.json files only.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const workspaces = ['apps', 'packages']
  .flatMap((d) => fs.readdirSync(path.join(root, d)).map((n) => path.join(root, d, n)))
  .filter((d) => fs.existsSync(path.join(d, 'package.json')));

/** Node-style resolution of a dependency's folder, starting from the dependant. */
function locate(name, from) {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (path.dirname(dir) === dir) return null;
  }
}

const seen = new Map();
const queue = workspaces.map((dir) => ({ dir, root: true }));
while (queue.length) {
  const { dir, root: isRoot } = queue.pop();
  const pkg = readJson(path.join(dir, 'package.json'));
  if (!isRoot) {
    const key = `${pkg.name}@${pkg.version}`;
    if (seen.has(key)) continue;
    const licence =
      typeof pkg.license === 'string'
        ? pkg.license
        : (pkg.license?.type ??
          (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN'));
    seen.set(key, {
      name: pkg.name,
      version: pkg.version,
      licence,
      repository: typeof pkg.repository === 'string' ? pkg.repository : (pkg.repository?.url ?? ''),
    });
  }
  for (const dep of Object.keys({ ...pkg.dependencies, ...(isRoot ? {} : pkg.optionalDependencies) })) {
    if (dep.startsWith('@vectora/')) continue;
    const found = locate(dep, dir);
    if (found) queue.push({ dir: found, root: false });
  }
}

const list = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const counts = {};
for (const p of list) counts[p.licence] = (counts[p.licence] ?? 0) + 1;
const permissive =
  /^(\(?(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|Unlicense|CC0-1\.0|BlueOak-1\.0\.0|Python-2\.0|CC-BY-4\.0|OFL-1\.1|Zlib|MPL-2\.0)( (OR|AND) )?)+\)?$/;
const review = list.filter((p) => !permissive.test(p.licence));

const lines = [
  '# Dependency licence inventory',
  '',
  `Generated by \`npm run licenses\` on ${new Date().toISOString().slice(0, 10)} from the installed packages. It covers the production dependency closure of every workspace (${list.length} packages); development tools are not included.`,
  '',
  '## Summary',
  '',
  '| Licence | Packages |',
  '|---|---:|',
  ...Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([l, c]) => `| ${l} | ${c} |`),
  '',
  '## Needs review',
  '',
  review.length
    ? 'These packages declare a licence outside the permissive set used for the automatic check:'
    : 'None. Every package declares a permissive licence (MIT, ISC, BSD, Apache-2.0, 0BSD, MPL-2.0, OFL-1.1 or equivalent).',
  '',
  ...review.map((p) => `- ${p.name}@${p.version}: ${p.licence}`),
  ...(review.length ? [''] : []),
  '## Bundled assets that are not npm packages',
  '',
  '| Asset | Version | Licence |',
  '|---|---|---|',
  '| tree-sitter-java grammar (WASM) | 0.23.5 | MIT |',
  '| tree-sitter-go grammar (WASM) | 0.25.0 | MIT |',
  '| tree-sitter-rust grammar (WASM) | 0.24.0 | MIT |',
  '| tree-sitter-c grammar (WASM) | 0.24.1 | MIT |',
  '| tree-sitter-cpp grammar (WASM) | 0.23.4 | MIT |',
  '| tree-sitter-c-sharp grammar (WASM) | 0.23.5 | MIT |',
  '| Zen Kaku Gothic New, Shippori Mincho, IBM Plex Mono (via @fontsource) | — | SIL OFL 1.1 |',
  '',
  '## Packages',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...list.map((p) => `| ${p.name} | ${p.version} | ${p.licence} |`),
  '',
];
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'LICENSES.md'), lines.join('\n'));
console.log(`${list.length} packages; ${review.length} need review. Written to docs/LICENSES.md`);
for (const p of review) console.log(`  review: ${p.name}@${p.version} — ${p.licence}`);
